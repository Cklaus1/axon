#[test]
fn a_tag_that_is_not_the_cargo_version_is_refused() {
    let body = format!(
        "{}\n\n- a fix.\n\n{}\n\n- first.\n",
        heading("0.1.1", 1, CARD1),
        heading("0.1.0", 1, CARD1)
    );
    let cl = format!("# Axon Changelog\n\n{body}");
    let t = tree(&cl, "0.1.1", "0.1.1", &[CARD1]);
    let (rc, out, err) = ledger(&t.0, &["--tag", "v0.1.1"]);
    assert_eq!(rc, 0, "the matching tag is refused:\n{out}{err}");
    let (rc, out, err) = ledger(&t.0, &["--tag", "v0.2.0"]);
    assert_eq!(
        rc, 1,
        "ATTACK: a tag was accepted that is not the released version\n{out}{err}"
    );
    assert!(err.contains("v0.2.0"), "{err}");
    // Unreleased text above the newest heading: the tag would not cover it.
    let cl = format!("# Axon Changelog\n\n## Batch 9: later\n\n- unreleased.\n\n{body}");
    let t = tree(&cl, "0.1.1", "0.1.1", &[CARD1]);
    let (rc, out, err) = ledger(&t.0, &[]);
    assert_eq!(
        rc, 0,
        "unreleased text is legal between releases:\n{out}{err}"
    );
    let (rc, out, err) = ledger(&t.0, &["--tag", "v0.1.1"]);
    assert_eq!(
        rc, 1,
        "ATTACK: a tag was accepted that is not the released version (unreleased text above it)\n{out}{err}"
    );
}

