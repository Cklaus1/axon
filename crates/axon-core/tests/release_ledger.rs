//! `scripts/release_ledger.py` (release-contract RC-3): every release heading
//! in `CHANGELOG.md` names a card version from `card-versions.txt`, and a
//! release whose section records a behaviour change, or whose card changed,
//! bumps MINOR (`spec/stability.md` rules 3, 4 and 6). The fixtures are whole
//! trees (`CHANGELOG.md`, `Cargo.toml`, `Cargo.lock`, member manifests and
//! `card-versions.txt`) written to a temp dir; the first test reads the repo.

mod script_spawn;
use script_spawn::{repo_root, script, Bins};
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicUsize, Ordering};

/// Card 1 at RC-2 (`crates/axon-core/card-versions.txt` line 1).
const CARD1: &str = "b70a0b560b5b84eb1873629cb6913caa902554ce29d29ef8d83834907bfeb05c";
const CARD2: &str = "2222222222222222222222222222222222222222222222222222222222222222";
const CARD3: &str = "3333333333333333333333333333333333333333333333333333333333333333";

static SEQ: AtomicUsize = AtomicUsize::new(0);

struct Tree(PathBuf);

impl Drop for Tree {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.0);
    }
}

fn write(root: &Path, rel: &str, text: &str) {
    let p = root.join(rel);
    std::fs::create_dir_all(p.parent().unwrap()).unwrap();
    std::fs::write(p, text).unwrap();
}

/// A fixture tree: `changelog`, workspace version `version`, an inheriting
/// member `axon-core` locked at `core_lock`, a self-versioned member
/// `axon-ai` (`version = "0.1.0"`, locked at 0.1.0), and `cards` as the lines
/// of `card-versions.txt` (`N` = position).
fn tree(changelog: &str, version: &str, core_lock: &str, cards: &[&str]) -> Tree {
    let root = std::env::temp_dir().join(format!(
        "axon-release-ledger-{}-{}",
        std::process::id(),
        SEQ.fetch_add(1, Ordering::SeqCst)
    ));
    let _ = std::fs::remove_dir_all(&root);
    write(&root, "CHANGELOG.md", changelog);
    write(
        &root,
        "Cargo.toml",
        &format!(
            "[workspace]\nmembers = [\n  \"crates/axon-core\",\n  \"crates/axon-ai\",\n]\nresolver = \"2\"\n\n\
             [workspace.package]\nversion = \"{version}\"\nedition = \"2021\"\n"
        ),
    );
    write(
        &root,
        "crates/axon-core/Cargo.toml",
        "[package]\nname = \"axon-core\"\nversion.workspace = true\nedition.workspace = true\n",
    );
    write(
        &root,
        "crates/axon-ai/Cargo.toml",
        "[package]\nname = \"axon-ai\"\nversion = \"0.1.0\"\nedition = \"2021\"\n",
    );
    write(
        &root,
        "Cargo.lock",
        &format!(
            "# This file is automatically @generated by Cargo.\nversion = 4\n\n\
             [[package]]\nname = \"axon-ai\"\nversion = \"0.1.0\"\n\n\
             [[package]]\nname = \"axon-core\"\nversion = \"{core_lock}\"\n"
        ),
    );
    let lines: String = cards
        .iter()
        .enumerate()
        .map(|(i, s)| format!("{} {s}\n", i + 1))
        .collect();
    write(&root, "crates/axon-core/card-versions.txt", &lines);
    Tree(root)
}

/// `release_ledger.py --root ROOT ARGS...`: (rc, stdout, stderr).
fn ledger(root: &Path, args: &[&str]) -> (i32, String, String) {
    let r = repo_root();
    let o = script(
        "python3",
        r.join("scripts/release_ledger.py"),
        Bins::NoWorkspaceBinary,
    )
    .arg("--root")
    .arg(root)
    .args(args)
    .current_dir(&r)
    .env("PYTHONDONTWRITEBYTECODE", "1")
    .env_remove("PYTHONPATH")
    .output()
    .unwrap();
    (
        o.status.code().unwrap_or(-1),
        String::from_utf8_lossy(&o.stdout).into_owned(),
        String::from_utf8_lossy(&o.stderr).into_owned(),
    )
}

fn heading(v: &str, card: usize, sha: &str) -> String {
    format!("## v{v} - 2026-11-20 (card {card}, {})", &sha[..8])
}

#[test]
fn the_repo_changelog_and_versions_agree() {
    let (rc, out, err) = ledger(&repo_root(), &[]);
    assert_eq!(rc, 0, "the release ledger refuses the repo:\n{out}{err}");
    assert!(out.contains("release_ledger: PASS ("), "{out}{err}");
}

#[test]
fn a_behaviour_change_without_a_minor_bump_is_refused() {
    let cl = format!(
        "# Axon Changelog\n\n{}\n\n- **Behaviour change:** a program that ran is now refused.\n\n{}\n\n- a fix.\n",
        heading("0.1.1", 1, CARD1),
        heading("0.1.0", 1, CARD1)
    );
    let t = tree(&cl, "0.1.1", "0.1.1", &[CARD1]);
    let (rc, out, err) = ledger(&t.0, &[]);
    assert_eq!(
        rc, 1,
        "ATTACK: a behaviour change shipped without a MINOR bump\n{out}{err}"
    );
    assert!(err.contains("v0.1.1"), "{err}");
}

