#[test]
fn the_section_query_reports_a_behaviour_change() {
    let cl = format!(
        "# Axon Changelog\n\n{}\n\n- **Behaviour change (x):** refused now.\n\n{}\n\n- a fix.\n",
        heading("0.2.0", 1, CARD1),
        heading("0.1.0", 1, CARD1)
    );
    let t = tree(&cl, "0.2.0", "0.2.0", &[CARD1]);
    let (rc, out, err) = ledger(&t.0, &["--section-has-behaviour-change", "v0.2.0"]);
    assert_eq!((rc, out.as_str()), (0, "1\n"), "{err}");
    let (rc, out, err) = ledger(&t.0, &["--section-has-behaviour-change", "v0.1.0"]);
    assert_eq!(
        (rc, out.as_str()),
        (0, "0\n"),
        "ATTACK: the release ledger hides a behaviour change from the compat diff\n{err}"
    );
    let (rc, _, _) = ledger(&t.0, &["--section-has-behaviour-change", "v0.3.0"]);
    assert_eq!(rc, 1, "a query for an absent release must fail");
}

#[test]
fn release_ledger_controls_pass() {
    // A PATCH release with no behaviour change.
    let patch = format!(
        "# Axon Changelog\n\n{}\n\n- a fix. Behaviour changes: none (unbolded, not a marker).\n\n{}\n\n- first.\n",
        heading("0.1.1", 1, CARD1),
        heading("0.1.0", 1, CARD1)
    );
    let t = tree(&patch, "0.1.1", "0.1.1", &[CARD1]);
    let (rc, out, err) = ledger(&t.0, &[]);
    assert_eq!(rc, 0, "a PATCH release was refused:\n{out}{err}");
    assert!(out.contains("release_ledger: PASS (2 releases)"), "{out}");
    // A MINOR release with a behaviour change and a card change.
    let minor = format!(
        "# Axon Changelog\n\n{}\n\n- **Behaviour change, arm c:** refused now; card 2.\n\n{}\n\n- first.\n",
        heading("0.2.0", 2, CARD2),
        heading("0.1.0", 1, CARD1)
    );
    let t = tree(&minor, "0.2.0", "0.2.0", &[CARD1, CARD2]);
    let (rc, out, err) = ledger(&t.0, &["--tag", "v0.2.0"]);
    assert_eq!(rc, 0, "a MINOR release was refused:\n{out}{err}");
    // No release heading: nothing released, so the default mode passes and a tag is refused.
    let none = "# Axon Changelog\n\n## Batch 1: x\n\n- **Behaviour change:** y.\n";
    let t = tree(none, "0.1.0", "0.1.0", &[CARD1]);
    let (rc, out, err) = ledger(&t.0, &[]);
    assert_eq!(rc, 0, "{out}{err}");
    assert!(out.contains("release_ledger: PASS (0 releases)"), "{out}");
    let (rc, _, _) = ledger(&t.0, &["--tag", "v0.1.0"]);
    assert_eq!(rc, 1, "a tag with no release heading was accepted");
    // The self-versioned member (`axon-ai`, locked at 0.1.0) is not held to 0.2.0,
    // and an unreleased last card line may be rewritten (nothing shipped it).
    let t = tree(&minor, "0.2.0", "0.2.0", &[CARD1, CARD2, CARD3]);
    let (rc, out, err) = ledger(&t.0, &[]);
    assert_eq!(
        rc, 0,
        "an unreleased card line or a self-versioned crate was refused:\n{out}{err}"
    );
}

/// `compat_sweep.py --diff OLD NEW --section-has-behaviour-change FLAG` over two
/// `compat.tsv` fixtures (release-contract RC-5): (rc, stdout, stderr).
fn compat_diff(old: &str, new: &str, flag: &str) -> (i32, String, String) {
    let dir = std::env::temp_dir().join(format!(
        "axon-compat-diff-{}-{}",
        std::process::id(),
        SEQ.fetch_add(1, Ordering::SeqCst)
    ));
    std::fs::create_dir_all(&dir).unwrap();
    let t = Tree(dir);
    write(&t.0, "old.tsv", old);
    write(&t.0, "new.tsv", new);
    let r = repo_root();
    let o = script(
        "python3",
        r.join("scripts/compat_sweep.py"),
        Bins::NoWorkspaceBinary,
    )
    .arg("--diff")
    .arg(t.0.join("old.tsv"))
    .arg(t.0.join("new.tsv"))
    .args(["--section-has-behaviour-change", flag])
    .current_dir(&r)
    .env("PYTHONDONTWRITEBYTECODE", "1")
    .env_remove("PYTHONPATH")
    .output()
    .unwrap();
    (
        o.status.code().unwrap_or(-1),
        String::from_utf8_lossy(&o.stdout).into_owned(),
        String::from_utf8_lossy(&o.stderr).into_owned(),
    )
}

#[test]
fn a_tracked_program_newly_refused_needs_a_behaviour_change() {
    let old = "a.ax\t0\t-\nb.ax\t0\t-\n";
    let new = "a.ax\t2\tE0102\nb.ax\t0\t-\n";
    let (rc, out, err) = compat_diff(old, new, "0");
    assert_eq!(
        rc, 1,
        "ATTACK: a newly refused tracked program shipped without a behaviour change\n{out}{err}"
    );
    assert!(
        out.contains("NEWLY REFUSED") && out.contains("a.ax"),
        "{out}"
    );
    assert!(!out.contains("b.ax"), "an unchanged file was listed: {out}");
}

#[test]
fn compat_diff_controls_pass() {
    // The same refusal, recorded as a behaviour change.
    let (rc, out, err) = compat_diff("a.ax\t0\t-\n", "a.ax\t2\tE0102\n", "1");
    assert_eq!(
        rc, 0,
        "a recorded behaviour change was refused:\n{out}{err}"
    );
    assert!(out.contains("NEWLY REFUSED"), "{out}");
    // A newly accepted file alone is informational.
    let (rc, out, err) = compat_diff("a.ax\t2\tE0102\n", "a.ax\t0\t-\n", "0");
    assert_eq!(rc, 0, "{out}{err}");
    assert!(out.contains("NEWLY ACCEPTED"), "{out}");
    // Same rc and first code (only the diagnostic text moved, which the TSV never
    // holds), a file only in one sweep, and a refusal whose code changed: rc 0.
    let (rc, out, err) = compat_diff(
        "a.ax\t2\tE0901\nc.ax\t2\tE0001\nold_only.ax\t0\t-\n",
        "a.ax\t2\tE0901\nc.ax\t2\tE0102\nnew_only.ax\t2\tE0001\n",
        "0",
    );
    assert_eq!(rc, 0, "{out}{err}");
    assert!(!out.contains("a.ax"), "an unchanged file was listed: {out}");
    assert!(
        out.contains("c.ax"),
        "a changed first code was not listed: {out}"
    );
}
