#!/usr/bin/env python3
"""Positive controls and power for the receipt corpus (PREREG-regress amendment 3).

A repair-path receipt is only worth having if it FAILS a build that really
repairs less. This script judges deliberately degraded Cortex builds (one-line
patches, `patches/*.diff`, built in a throwaway worktree and never committed to
`crates/axon-cortex/src/`) against main's receipt run, twice:

  old rule  the dev corpus alone (amendment 2: 60 tasks, main at 60/60)
  new rule  the pooled receipt corpus (amendment 3: dev + hard-dev in-scope +
            tempt, 115 tasks)

Both apply `scorecard.receipt_rule` unchanged: only the set of tasks differs.
It then computes the power of the new rule: the exact probability that a true
loss of k fixes, on top of the discordance two runs of MAIN already show,
reaches exact McNemar p < 0.05.

The degraded builds' rows were produced per leg (`../ceiling/explore/LEG-BUILD-h55`)
by `ab/run_ab.py --arm B` with the receipt config. Main's rows and its replicate
are history runs (`--main`, `--replicate`; default: the first two receipt-set
runs with no incumbent).

    python3 controls.py            write README.md
    python3 controls.py --check    exit 1 unless README.md is what the rows give
"""
import argparse
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SC = os.path.dirname(HERE)
sys.path.insert(0, SC)
import scorecard as S  # noqa: E402

analyse = S.analyse
EXPLORE = os.path.join(SC, "ceiling", "explore")
README = os.path.join(HERE, "README.md")
# (build, what the one-line patch does, leg dir stems)
BUILDS = (
    ("context-off", "`runner.rs`: the generator is never shown the file or the failing "
     "checks (`GenContext::BodyOnly`); it sees the body alone.", "dctx"),
    ("source-off", "`generate.rs`: the prompt's file source is blanked.", "d3"),
    ("feedback-off", "`generate.rs`: neither the retry feedback nor the current visible-test "
     "output reaches the prompt (the user's example of a degrade).", "d12"),
)
LEG_DIRS = {"dev": "dev-{b}-h55", "hard-dev": "harddev-{b}-h55", "tempt": "tempt-{b}-h55"}


def leg_ids(spec):
    return {k: list(v) for k, v in spec["legs"].items()}


def load_build(stem, legs, truth):
    """Normalized rows of one degraded build over the receipt corpus: each leg's
    explore rows, restricted to the receipt corpus's task ids."""
    out = []
    for leg, ids in legs.items():
        path = os.path.join(EXPLORE, LEG_DIRS[leg].format(b=stem), "b.jsonl")
        keep = set(ids)
        rows = [r for r in S.read_jsonl(path) if r["id"] in keep]
        out += [S.normalize(r, truth) for r in rows]
    return out


def judge_rows(a, b):
    """`receipt_rule` for candidate rows b against incumbent rows a, on the
    tasks in both: (verdict, paired, effort, false successes)."""
    ids = {r["id"] for r in a} & {r["id"] for r in b}
    a = [r for r in a if r["id"] in ids]
    b = [r for r in b if r["id"] in ids]
    p = S.pair(b, a)
    effort = [S.sign_test(a, b, k, name) for k, name in S.EFFORT]
    fs = sum(1 for r in b if r["false_success"])
    return S.receipt_rule(fs, p, effort), p, len(ids), sum(r["verified"] for r in a), \
        sum(r["verified"] for r in b)


def power(n_noise, k, alpha=S.ALPHA):
    """P(exact two-sided McNemar p < alpha with more losses than gains) when
    `n_noise` discordant pairs fall either way with probability 1/2 each (the
    discordance two runs of the same code show) and k further tasks are truly
    lost."""
    tot = 0.0
    for lost_noise in range(n_noise + 1):
        losses, gains = lost_noise + k, n_noise - lost_noise
        if losses > gains and analyse.mcnemar_exact(losses, gains) < alpha:
            tot += math.comb(n_noise, lost_noise) / 2 ** n_noise
    return tot


def min_k(n_noise, target):
    k = 0
    while power(n_noise, k) < target:
        k += 1
        if k > 200:
            return None
    return k


def render(history):
    spec = S.receipt_spec(S.ROOT)
    legs = leg_ids(spec)
    truth = S.load_corpus(spec["corpus"])
    runs, _ = S.load_records(history)
    norms = S.verify(runs, S.ROOT)
    import json
    corpus_sha = S.sha256_file(spec["corpus"])
    mains = [r for r in S.ordered(runs) if r["set"] == S.RECEIPT_SET and r["agent"] == "cortex"
             and r["corpus"]["sha256"] == corpus_sha and not r.get("receipt_incumbent")]
    if len(mains) < 2:
        raise S.Refused("controls need two receipt runs of main with no incumbent (main's run and "
                        "its replicate): `scorecard.py regress --main-only`, twice")
    main, rep = mains[0], mains[1]
    a, rb = norms[main["run_id"]], norms[rep["run_id"]]
    out = ["# Receipt controls and power (PREREG-regress amendment 3)", "",
           "Generated by `controls.py` from committed rows; `python3 controls.py --check` "
           "fails if this page is stale. Nothing here is typed by hand.", "",
           "## Incumbent and null", "",
           f"Main's receipt run `{main['run_id']}` ({main['metrics']['verified']}/"
           f"{main['metrics']['n']} verified) and its replicate `{rep['run_id']}` "
           f"({rep['metrics']['verified']}/{rep['metrics']['n']}): the same code, the same "
           "config, run twice.", ""]
    nul, np_, n, va, vb = judge_rows(a, rb)
    nz = np_["only_this"] + np_["only_baseline"]
    out += [f"Replicate against main, pooled: verified {va} -> {vb} of {n}, discordant pairs "
            f"{nz} (only main {np_['only_baseline']}, only replicate {np_['only_this']}), exact "
            f"McNemar p = {np_['mcnemar_p']:.3g}; the rule says "
            f"**{'WORSE' if nul['worse'] else 'not worse'}** ({nul['reason']}).", "",
            "| leg | tasks | main verified | replicate verified | only main | only replicate | "
            "McNemar p |", "|---|---|---|---|---|---|---|"]
    for leg, ids in legs.items():
        s = set(ids)
        _, p, nn, x, y = judge_rows([r for r in a if r["id"] in s], [r for r in rb if r["id"] in s])
        out.append(f"| {leg} | {nn} | {x} | {y} | {p['only_baseline']} | {p['only_this']} | "
                   f"{p['mcnemar_p']:.3g} |")
    out += ["", "## Degraded builds, judged by the old and the new rule", "",
            "Each build is `main` plus the one-line patch in `patches/`. A cell is "
            "`main verified -> build verified`. The old rule sees the dev leg only; the "
            "new rule sees all 115 tasks pooled. Both are `receipt_rule` (a false success, a "
            "significant verified loss, then a significant effort loss).", "",
            "| build | dev | hard-dev | tempt | pooled only main / only build, McNemar p | "
            "old rule (dev alone) | new rule (pooled) |", "|---|---|---|---|---|---|---|"]
    for name, _what, stem in BUILDS:
        b = load_build(stem, legs, truth)
        cells, per = [], {}
        for leg, ids in legs.items():
            s = set(ids)
            v, p, nn, x, y = judge_rows([r for r in a if r["id"] in s], [r for r in b if r["id"] in s])
            cells.append(f"{x} -> {y} of {nn}")
            per[leg] = v
        v, p, nn, x, y = judge_rows(a, b)
        old = per["dev"]
        out.append(f"| {name} | " + " | ".join(cells) + f" | {p['only_baseline']} / "
                   f"{p['only_this']}, p = {p['mcnemar_p']:.3g} | "
                   f"{'**WORSE**' if old['worse'] else 'not worse'}: {old['reason']} | "
                   f"{'**WORSE**' if v['worse'] else 'not worse'}: {v['reason']} |")
    out += ["", "What each patch does:", ""]
    out += [f"- **{name}**: {what} (`patches/{stem}.diff`)" for name, what, stem in BUILDS]
    dev = set(legs["dev"])
    dn = judge_rows([r for r in a if r["id"] in dev], [r for r in rb if r["id"] in dev])[1]
    dnz = dn["only_this"] + dn["only_baseline"]
    out += ["", "## Power of the pooled receipt", "",
            f"Two runs of the same code differ on {nz} of {n} tasks (above). Model: those "
            f"{nz} discordant pairs fall either way with probability 1/2, and k further tasks "
            "are truly lost. P(reject) is the exact probability that the exact two-sided "
            f"McNemar test gives p < {S.ALPHA} with more losses than gains (the verified step "
            f"of `receipt_rule`). The dev leg alone shows {dnz} discordant pairs: main scores "
            f"{sum(r['verified'] for r in a if r['id'] in dev)}/60 there, so even with no gains "
            f"{min_k(0, 1.0)} fixes ({100 * min_k(0, 1.0) / 60:.0f}% of the leg) must be lost "
            "before the verified step can fire.", "",
            "| true loss k | P(reject), pooled | P(reject), dev leg alone |", "|---|---|---|"]
    for k in (0, 1, 2, 3, 4, 5, 6, 8, 10, 12):
        out.append(f"| {k} | {power(nz, k):.3f} | {power(dnz, k):.3f} |")
    out += ["", f"Smallest true loss detected with probability at least 0.5 / 0.8 / 0.95: "
            f"pooled {min_k(nz, 0.5)} / {min_k(nz, 0.8)} / {min_k(nz, 0.95)} tasks "
            f"(of {n}); dev leg alone {min_k(dnz, 0.5)} / {min_k(dnz, 0.8)} / "
            f"{min_k(dnz, 0.95)} tasks (of 60).", ""]
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--history", default=S.HISTORY)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    text = render(a.history)
    if a.check:
        have = open(README).read() if os.path.exists(README) else None
        if have != text:
            print("controls/README.md is stale: run `python3 controls.py`", file=sys.stderr)
            return 1
        return 0
    with open(README, "w") as fh:
        fh.write(text)
    print(f"wrote {README}")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except S.Refused as e:
        print(f"refused: {e}", file=sys.stderr)
        sys.exit(2)
