//! The protected guest image is built in an environment the build CONSTRUCTS
//! (scripts/guest_build_env.py), not one it filters by a list of names
//! (C9 round 4, FIELD-ORIGIN / PSV-2 / EQUIVALENCE; two reviewers built
//! through an ancestor `.cargo/config.toml`, a dotted `build.rustc-wrapper`,
//! RUSTC/RUSTFLAGS and a reused target dir, and the old guard passed each).
//!
//! C9 round 4b (FIELD-ORIGIN, amendment 63): the build runs on a PRIVATE copy
//! of the tracked tree under a directory only root or the builder can write,
//! with cargo's effective config held to begin's before and after EVERY
//! invocation; only the table's exact invocations run; and the kernel and the
//! rootfs are made in the same discipline.
//!
//! These run the PRODUCTION route: `scripts/build-guest-image.sh
//! --build-env-only`, the same `gcargo_begin` every guest build starts with,
//! and the `guest_build_env.py cargo` / `rootfs` / `kernel` steps the image
//! build calls, from a scratch checkout of this tree's files.

#[path = "../../axon-core/tests/script_spawn/mod.rs"]
mod script_spawn;
use script_spawn::{repo_root, Bins};
use serde_json::Value;
use sha2::{Digest, Sha256};
use std::path::{Path, PathBuf};
use std::process::{Command, Output, Stdio};

/// The files the controlled-build step reads, copied from THIS tree.
const COPIED: [&str; 4] = [
    "scripts/build-guest-image.sh",
    "scripts/guest_build_env.py",
    "rust-toolchain.toml",
    ".cargo/config.toml",
];
const CRT: &str = "-C target-feature=+crt-static";
/// The protected `axon-guest-init` invocation (guest_build_env.py
/// PROTECTED_BUILDS), exactly: the checkout's one crate has that name.
const GUEST_INIT: [&str; 8] = [
    "build",
    "--locked",
    "-p",
    "axon-guest-init",
    "--target",
    "x86_64-unknown-linux-musl",
    "--release",
    "--quiet",
];

fn write(p: &Path, s: &str) {
    std::fs::create_dir_all(p.parent().unwrap()).unwrap();
    std::fs::write(p, s).unwrap();
}

fn chmod(p: &Path, mode: u32) {
    use std::os::unix::fs::PermissionsExt;
    std::fs::set_permissions(p, std::fs::Permissions::from_mode(mode)).unwrap();
}

fn chmod_x(p: &Path) {
    chmod(p, 0o755);
}

fn sha(p: &Path) -> String {
    format!("{:x}", Sha256::digest(std::fs::read(p).unwrap()))
}

fn git(r: &Path, args: &[&str]) {
    let st = Command::new("/usr/bin/git")
        .arg("-C")
        .arg(r)
        .args(["-c", "user.name=t", "-c", "user.email=t@example"])
        .args(args)
        .stdout(Stdio::null())
        .status()
        .unwrap();
    assert!(st.success(), "git {args:?}");
}

/// A git checkout at `<parent>/repo` holding the build's files and a one-crate
/// workspace whose crate is named `axon-guest-init` (no dependencies, so a
/// fresh CARGO_HOME builds it offline), plus a rootfs profile whose busybox
/// is a fixture at `<parent>/busybox`. The build copies its TRACKED files.
fn checkout(parent: &Path) -> PathBuf {
    let r = parent.join("repo");
    for f in COPIED {
        write(
            &r.join(f),
            &std::fs::read_to_string(repo_root().join(f)).unwrap(),
        );
    }
    write(
        &r.join("Cargo.toml"),
        "[workspace]\nmembers = [\"guest\"]\nresolver = \"2\"\n",
    );
    write(
        &r.join("guest/Cargo.toml"),
        "[package]\nname = \"axon-guest-init\"\nversion = \"0.0.0\"\nedition = \"2021\"\n",
    );
    write(&r.join("guest/src/main.rs"), "fn main() {}\n");
    write(
        &r.join("Cargo.lock"),
        "# This file is automatically @generated by Cargo.\n# It is not intended for manual \
         editing.\nversion = 4\n\n[[package]]\nname = \"axon-guest-init\"\nversion = \"0.0.0\"\n",
    );
    let bb = parent.join("busybox");
    write(&bb, "#!/bin/sh\necho sh\necho ls\necho busybox\n");
    chmod_x(&bb);
    write(
        &r.join("profiles/linux-microvm/kernel.pin"),
        &format!(
            "BUSYBOX_SRC={}\nBUSYBOX_SHA256={}\n",
            bb.display(),
            sha(&bb)
        ),
    );
    write(
        &r.join("profiles/linux-microvm/guest-init.sh"),
        "#!/bin/sh\necho init\n",
    );
    git(&r, &["init", "-q", "-b", "main"]);
    git(&r, &["add", "-A"]);
    r
}

/// `build-guest-image.sh --build-env-only <out>`: the controlled environment
/// alone, recorded in `<out>/build-env.json`.
fn build_env_only(repo: &Path, out: &Path, env: &[(&str, String)]) -> Output {
    let mut c = script_spawn::script(
        "bash",
        repo.join("scripts/build-guest-image.sh"),
        Bins::BuildsItsOwn,
    );
    c.arg("--build-env-only")
        .arg(out)
        .current_dir(repo)
        .env("AXON_GUEST_BUILD_PARENT", test_parent());
    for (k, v) in env {
        c.env(k, v);
    }
    c.output().unwrap()
}

/// Where a real controlled build keeps its private directories and proof keys.
fn real_parent() -> PathBuf {
    PathBuf::from(std::env::var("HOME").unwrap())
        .join(".cache")
        .join("axon-guest-build")
}

/// The build parent every build these tests start uses: a directory made for
/// THIS test process under the builder's home (only root's or the builder's
/// ancestors), removed at exit. Never `~/.cache/axon-guest-build`: a test run
/// must not leave keys or build directories in the real builder-private place.
fn test_parent() -> &'static Path {
    use std::os::unix::fs::PermissionsExt;
    static P: std::sync::OnceLock<PathBuf> = std::sync::OnceLock::new();
    static CLEAN: std::sync::OnceLock<std::ffi::CString> = std::sync::OnceLock::new();
    P.get_or_init(|| {
        let d = PathBuf::from(std::env::var("HOME").unwrap())
            .join(".cache")
            .join(format!("axon-gbe-test-{}", std::process::id()));
        std::fs::create_dir_all(&d).unwrap();
        std::fs::set_permissions(&d, std::fs::Permissions::from_mode(0o700)).unwrap();
        assert!(
            !d.starts_with(real_parent()),
            "ATTACK: a test would build under the real builder-private parent"
        );
        extern "C" fn clean() {
            if let Some(p) = CLEAN.get() {
                let _ = std::fs::remove_dir_all(p.to_str().unwrap());
            }
        }
        CLEAN
            .set(std::ffi::CString::new(d.to_str().unwrap()).unwrap())
            .unwrap();
        unsafe { libc::atexit(clean) };
        d.join("parent")
    })
}

/// `guest_build_env.py ...` from the checkout.
fn gbe(repo: &Path) -> Command {
    let mut c = script_spawn::script(
        "python3",
        repo.join("scripts/guest_build_env.py"),
        Bins::BuildsItsOwn,
    );
    c.current_dir(repo)
        .env("AXON_GUEST_BUILD_PARENT", test_parent());
    c
}

/// `guest_build_env.py cargo REC [--rustflags F] -- ARGS`: one controlled step.
fn gcargo(repo: &Path, rec: &Path, rustflags: Option<&str>, args: &[&str]) -> Output {
    let mut c = gbe(repo);
    c.arg("cargo").arg(rec);
    if let Some(f) = rustflags {
        c.args(["--rustflags", f]);
    }
    c.arg("--").args(args);
    c.output().unwrap()
}

fn record(out: &Path) -> Value {
    let rec: Value =
        serde_json::from_slice(&std::fs::read(out.join("build-env.json")).unwrap()).unwrap();
    let parent = PathBuf::from(rec["build_parent"].as_str().unwrap_or("/"));
    assert!(
        !parent.starts_with(real_parent()),
        "ATTACK: a test built under the real builder-private parent {}",
        parent.display()
    );
    rec
}

/// The private build directory (the parent of the fresh target dir).
fn base_of(rec: &Value) -> PathBuf {
    Path::new(rec["target_dir"].as_str().unwrap())
        .parent()
        .unwrap()
        .to_path_buf()
}

/// Remove the private build directory a successful begin created.
fn discard(rec: &Value) {
    if rec["target_dir"].as_str().is_some() {
        let base = base_of(rec);
        if base
            .file_name()
            .is_some_and(|n| n.to_string_lossy().starts_with("axon-guest-build-"))
        {
            let _ = std::fs::remove_dir_all(base);
        }
    }
}

fn text(o: &Output) -> String {
    format!(
        "{}{}",
        String::from_utf8_lossy(&o.stdout),
        String::from_utf8_lossy(&o.stderr)
    )
}

/// A scratch directory under the builder's home: its ancestors are only
/// root's or the builder's, so it may hold a build parent.
fn private_scratch() -> tempfile::TempDir {
    let cache = PathBuf::from(std::env::var("HOME").unwrap()).join(".cache");
    std::fs::create_dir_all(&cache).unwrap();
    tempfile::tempdir_in(cache).unwrap()
}

/// A rustc wrapper that leaves `marker` behind and runs the compiler.
fn wrapper(dir: &Path, marker: &Path) -> PathBuf {
    let w = dir.join("wrapper");
    write(
        &w,
        &format!("#!/bin/sh\n: > '{}'\nexec \"$@\"\n", marker.display()),
    );
    chmod_x(&w);
    w
}

/// A begun controlled build of a fresh checkout under `d`: (repo, record path, record).
fn begun(d: &Path) -> (PathBuf, PathBuf, Value) {
    let r = checkout(d);
    let out = d.join("out");
    let o = build_env_only(&r, &out, &[]);
    assert!(o.status.success(), "setup: begin: {}", text(&o));
    let rec = record(&out);
    (r, out.join("build-env.json"), rec)
}

/// cargo's EFFECTIVE configuration, as it resolves it from the build's
/// directory, may hold nothing the guest build would use -- from an ancestor
/// directory's config, in the dotted-key spelling, or committed to the tree's
/// own config. Control: the tree's own config (wasm-only rustflags) passes.
#[test]
fn a_cargo_config_setting_the_guest_build_would_use_is_refused() {
    let cases: [(&str, &str, bool); 5] = [
        (
            "an ancestor .cargo/config.toml naming a rustc wrapper",
            "[build]\nrustc-wrapper = \"/usr/bin/sccache\"\n",
            false,
        ),
        (
            "an ancestor config in the dotted-key spelling",
            "build.rustc-wrapper = \"/usr/bin/sccache\"\n",
            false,
        ),
        (
            "an ancestor config naming a linker for the guest's target",
            "[target.x86_64-unknown-linux-musl]\nlinker = \"/tmp/evil-cc\"\n",
            false,
        ),
        (
            "an ancestor config adding rustflags",
            "[build]\nrustflags = [\"--cfg\", \"evil\"]\n",
            false,
        ),
        (
            "the tree's own config naming a rustc",
            "build.rustc = \"/tmp/evil-rustc\"\n",
            true,
        ),
    ];
    for (attack, cfg, own) in cases {
        let d = tempfile::tempdir().unwrap();
        let r = checkout(d.path());
        // The build parent's ancestors are where cargo, running in the private
        // copy, looks: a config there (written by root or the builder, the
        // only uids that can) is in its effective configuration.
        let scratch = private_scratch();
        let parent = scratch.path().join("parent");
        if own {
            let p = r.join(".cargo/config.toml");
            // At the top, so the dotted key is not inside the file's tables.
            let s = std::fs::read_to_string(&p).unwrap();
            write(&p, &format!("{cfg}{s}"));
            git(&r, &["add", "-A"]);
        } else {
            write(&scratch.path().join(".cargo/config.toml"), cfg);
        }
        let out = d.path().join("out");
        let o = build_env_only(
            &r,
            &out,
            &[("AXON_GUEST_BUILD_PARENT", parent.display().to_string())],
        );
        if o.status.success() {
            discard(&record(&out));
        }
        assert!(
            !o.status.success(),
            "ATTACK: the guest build ran under a cargo config setting it would use ({attack}):\n{}",
            text(&o)
        );
        assert!(
            text(&o).contains("effective configuration"),
            "{attack}: {}",
            text(&o)
        );
    }
    // Control: the tree's own config alone.
    let d = tempfile::tempdir().unwrap();
    let r = checkout(d.path());
    let out = d.path().join("out");
    let o = build_env_only(&r, &out, &[]);
    assert!(
        o.status.success(),
        "control: the tree's own config builds: {}",
        text(&o)
    );
    let rec = record(&out);
    discard(&rec);
    assert_eq!(rec["effective_config"]["foreign"], serde_json::json!([]));
}

/// Cargo runs in the environment the build constructs, never the caller's:
/// a RUSTC_WRAPPER (and friends) exported by whoever launched the build does
/// not reach the compile. Control: the step builds, into the fresh target dir.
#[test]
fn a_callers_compiler_wrapper_does_not_reach_the_guest_builds_cargo() {
    let d = tempfile::tempdir().unwrap();
    let (r, rec_path, _) = begun(d.path());
    let marker = d.path().join("wrapper-ran");
    let w = wrapper(d.path(), &marker);
    let mut c = gbe(&r);
    c.arg("cargo")
        .arg(&rec_path)
        .args(["--rustflags", CRT, "--"])
        .args(GUEST_INIT);
    for v in [
        "RUSTC_WRAPPER",
        "RUSTC_WORKSPACE_WRAPPER",
        "CARGO_BUILD_RUSTC_WRAPPER",
    ] {
        c.env(v, &w);
    }
    c.env("RUSTC", "/bin/false")
        .env("RUSTFLAGS", "--cfg evil")
        .env("CARGO_BUILD_RUSTC", "/bin/false");
    let b = c.output().unwrap();
    let rec: Value = serde_json::from_slice(&std::fs::read(&rec_path).unwrap()).unwrap();
    let built = gpath(&r, &rec_path, "axon-guest-init");
    let (ran, exists) = (marker.exists(), built.exists());
    discard(&rec);
    assert!(
        !ran,
        "ATTACK: a caller's RUSTC_WRAPPER reached the guest build's cargo:\n{}",
        text(&b)
    );
    assert!(
        b.status.success() && exists,
        "control: the controlled step builds, into the fresh target dir:\n{}",
        text(&b)
    );
}

/// The toolchain is the one rust-toolchain.toml pins, as rustup resolves it
/// under a CLEARED environment: a caller's RUSTUP_HOME holding a toolchain of
/// the same name does not choose the compiler. Control: the recorded rustc
/// is the invoking user's real toolchain.
#[test]
fn a_callers_rustup_home_does_not_choose_the_guest_toolchain() {
    let d = tempfile::tempdir().unwrap();
    let r = checkout(d.path());
    let chan = std::fs::read_to_string(r.join("rust-toolchain.toml"))
        .unwrap()
        .lines()
        .find_map(|l| {
            l.trim().strip_prefix("channel").map(|v| {
                v.split('=')
                    .nth(1)
                    .unwrap()
                    .trim()
                    .trim_matches('"')
                    .to_string()
            })
        })
        .unwrap();
    let fake_home = d.path().join("fake-rustup");
    let bin = fake_home.join(format!("toolchains/{chan}-x86_64-unknown-linux-gnu/bin"));
    for tool in ["cargo", "rustc"] {
        write(
            &bin.join(tool),
            "#!/bin/sh\ncase \"$*\" in *config*) exit 0;; esac\necho \"fake 1.0 (planted)\"\n",
        );
        chmod_x(&bin.join(tool));
    }
    let out = d.path().join("out");
    let o = build_env_only(
        &r,
        &out,
        &[
            ("RUSTUP_HOME", fake_home.display().to_string()),
            ("RUSTUP_TOOLCHAIN", chan.clone()),
        ],
    );
    let rec = if o.status.success() {
        record(&out)
    } else {
        Value::Null
    };
    discard(&rec);
    let rustc = rec["toolchain"]["rustc"].as_str().unwrap_or("");
    assert!(
        !rustc.starts_with(fake_home.to_str().unwrap()),
        "ATTACK: a caller's RUSTUP_HOME chose the guest build's compiler ({rustc})"
    );
    assert!(
        o.status.success() && Path::new(rustc).is_file(),
        "control: the pinned toolchain resolves: {}",
        text(&o)
    );
}

