fn write(p: &Path, s: &str) {
    std::fs::create_dir_all(p.parent().unwrap()).unwrap();
    std::fs::write(p, s).unwrap();
}

fn chmod(p: &Path, mode: u32) {
    use std::os::unix::fs::PermissionsExt;
    std::fs::set_permissions(p, std::fs::Permissions::from_mode(mode)).unwrap();
}

fn chmod_x(p: &Path) {
    chmod(p, 0o755);
}

fn sha(p: &Path) -> String {
    format!("{:x}", Sha256::digest(std::fs::read(p).unwrap()))
}

fn git(r: &Path, args: &[&str]) {
    let st = Command::new("/usr/bin/git")
        .arg("-C")
        .arg(r)
        .args(["-c", "user.name=t", "-c", "user.email=t@example"])
        .args(args)
        .stdout(Stdio::null())
        .status()
        .unwrap();
    assert!(st.success(), "git {args:?}");
}

/// A git checkout at `<parent>/repo` holding the build's files and a one-crate
/// workspace whose crate is named `axon-guest-init` (no dependencies, so a
/// fresh CARGO_HOME builds it offline), plus a rootfs profile whose busybox
/// is a fixture at `<parent>/busybox`. The build copies its TRACKED files.
fn checkout(parent: &Path) -> PathBuf {
    let r = parent.join("repo");
    for f in COPIED {
        write(
            &r.join(f),
            &std::fs::read_to_string(repo_root().join(f)).unwrap(),
        );
    }
    write(
        &r.join("Cargo.toml"),
        "[workspace]\nmembers = [\"guest\"]\nresolver = \"2\"\n",
    );
    write(
        &r.join("guest/Cargo.toml"),
        "[package]\nname = \"axon-guest-init\"\nversion = \"0.0.0\"\nedition = \"2021\"\n",
    );
    write(&r.join("guest/src/main.rs"), "fn main() {}\n");
    write(
        &r.join("Cargo.lock"),
        "# This file is automatically @generated by Cargo.\n# It is not intended for manual \
         editing.\nversion = 4\n\n[[package]]\nname = \"axon-guest-init\"\nversion = \"0.0.0\"\n",
    );
    let bb = parent.join("busybox");
    write(&bb, "#!/bin/sh\necho sh\necho ls\necho busybox\n");
    chmod_x(&bb);
    write(
        &r.join("profiles/linux-microvm/kernel.pin"),
        &format!(
            "BUSYBOX_SRC={}\nBUSYBOX_SHA256={}\n",
            bb.display(),
            sha(&bb)
        ),
    );
    write(
        &r.join("profiles/linux-microvm/guest-init.sh"),
        "#!/bin/sh\necho init\n",
    );
    git(&r, &["init", "-q", "-b", "main"]);
    git(&r, &["add", "-A"]);
    // Amendment 92: the rootfs step reads the profile's pin and guest-init.sh from the COMMITTED tree.
    git(&r, &["commit", "-q", "-m", "fixture"]);
    r
}

/// `build-guest-image.sh --build-env-only <out>`: the controlled environment
/// alone, recorded in `<out>/build-env.json`.
fn build_env_only(repo: &Path, out: &Path, env: &[(&str, String)]) -> Output {
    let mut c = script_spawn::script(
        "bash",
        repo.join("scripts/build-guest-image.sh"),
        Bins::BuildsItsOwn,
    );
    c.arg("--build-env-only")
        .arg(out)
        .current_dir(repo)
        .env("AXON_GUEST_BUILD_PARENT", test_parent())
        .env("AXON_GUEST_BUILD_UID", test_uid().to_string());
    for (k, v) in env {
        c.env(k, v);
    }
    c.output().unwrap()
}

/// Where a real controlled build keeps its private directories and proof keys
/// (the old default under the builder's home, and the system default): a test
/// never writes either.
fn real_parent() -> PathBuf {
    PathBuf::from("/var/lib/axon-guest-build")
}

fn old_real_parent() -> PathBuf {
    PathBuf::from(std::env::var("HOME").unwrap())
        .join(".cache")
        .join("axon-guest-build")
}

/// The directory test builds live under: reachable by the unprivileged uid the
/// build processes run as (a path under root's 0700 home is not), removed at exit.
const TEST_ROOT: &str = "/var/lib";

/// The build parent every build these tests start uses: a directory made for
/// THIS test process under the builder's home (only root's or the builder's
/// ancestors), removed at exit. Never `~/.cache/axon-guest-build`: a test run
/// must not leave keys or build directories in the real builder-private place.
fn test_parent() -> &'static Path {
    use std::os::unix::fs::PermissionsExt;
    static P: std::sync::OnceLock<PathBuf> = std::sync::OnceLock::new();
    static CLEAN: std::sync::OnceLock<std::ffi::CString> = std::sync::OnceLock::new();
    P.get_or_init(|| {
        let d = PathBuf::from(TEST_ROOT).join(format!("axon-gbe-test-{}", std::process::id()));
        std::fs::create_dir_all(&d).unwrap();
        std::fs::set_permissions(&d, std::fs::Permissions::from_mode(0o755)).unwrap();
        assert!(
            !d.starts_with(real_parent()) && !d.starts_with(old_real_parent()),
            "ATTACK: a test would build under the real builder-private parent"
        );
        extern "C" fn clean() {
            if let Some(p) = CLEAN.get() {
                let _ = std::fs::remove_dir_all(p.to_str().unwrap());
            }
        }
        CLEAN
            .set(std::ffi::CString::new(d.to_str().unwrap()).unwrap())
            .unwrap();
        unsafe { libc::atexit(clean) };
        d.join("parent")
    })
}

/// `inner` re-built to run in a PRIVATE PID namespace (`unshare --pid --fork --mount-proc
/// --kill-child`), optionally through `sh -c SCRIPT sh` first. Amendment 92: the runner kills every
/// process of the build uid after a step, and the default build uid (65534) is `nobody` on a dev host,
/// so no test may run it where it could see (and signal) the host's processes.
fn in_pid_ns(inner: &Command, script: Option<&str>) -> Command {
    let mut c = Command::new("/usr/bin/unshare");
    c.args(["--pid", "--fork", "--mount-proc", "--kill-child"]);
    if let Some(sc) = script {
        c.args(["sh", "-c", sc, "sh"]);
    }
    c.arg(inner.get_program()).args(inner.get_args());
    for (k, v) in inner.get_envs() {
        match v {
            Some(v) => c.env(k, v),
            None => c.env_remove(k),
        };
    }
    if let Some(d) = inner.get_current_dir() {
        c.current_dir(d);
    }
    c
}

/// `guest_build_env.py ...` from the checkout, in a private PID namespace.
fn gbe(repo: &Path) -> Command {
    in_pid_ns(&gbe_raw(repo), None)
}

/// The same, without the namespace: only for commands that run no build step.
fn gbe_raw(repo: &Path) -> Command {
    let mut c = script_spawn::script(
        "python3",
        repo.join("scripts/guest_build_env.py"),
        Bins::BuildsItsOwn,
    );
    c.current_dir(repo)
        .env("AXON_GUEST_BUILD_PARENT", test_parent())
        .env("AXON_GUEST_BUILD_UID", test_uid().to_string());
    c
}

/// `guest_build_env.py cargo REC [--rustflags F] -- ARGS`: one controlled step.
fn gcargo(repo: &Path, rec: &Path, rustflags: Option<&str>, args: &[&str]) -> Output {
    let mut c = gbe(repo);
    c.arg("cargo").arg(rec);
    if let Some(f) = rustflags {
        c.args(["--rustflags", f]);
    }
    c.arg("--").args(args);
    c.output().unwrap()
}

fn record(out: &Path) -> Value {
    let rec: Value =
        serde_json::from_slice(&std::fs::read(out.join("build-env.json")).unwrap()).unwrap();
    let parent = PathBuf::from(rec["build_parent"].as_str().unwrap_or("/"));
    assert!(
        !parent.starts_with(real_parent()) && !parent.starts_with(old_real_parent()),
        "ATTACK: a test built under the real builder-private parent {}",
        parent.display()
    );
    rec
}

/// The private build directory (the parent of the fresh target dir).
fn base_of(rec: &Value) -> PathBuf {
    Path::new(rec["target_dir"].as_str().unwrap())
        .parent()
        .unwrap()
        .to_path_buf()
}

/// Remove the private build directory a successful begin created.
fn discard(rec: &Value) {
    if rec["target_dir"].as_str().is_some() {
        let base = base_of(rec);
        if base
            .file_name()
            .is_some_and(|n| n.to_string_lossy().starts_with("axon-guest-build-"))
        {
            let _ = std::fs::remove_dir_all(base);
        }
    }
}

fn text(o: &Output) -> String {
    format!(
        "{}{}",
        String::from_utf8_lossy(&o.stdout),
        String::from_utf8_lossy(&o.stderr)
    )
}

/// A scratch directory under the builder's home: its ancestors are only
/// root's or the builder's, so it may hold a build parent.
fn private_scratch() -> tempfile::TempDir {
    use std::os::unix::fs::PermissionsExt;
    let d = tempfile::Builder::new()
        .prefix("axon-gbe-scratch-")
        .tempdir_in(TEST_ROOT)
        .unwrap();
    std::fs::set_permissions(d.path(), std::fs::Permissions::from_mode(0o755)).unwrap();
    d
}

/// A rustc wrapper that leaves `marker` behind and runs the compiler.
fn wrapper(_dir: &Path, marker: &Path) -> PathBuf {
    // Where the unprivileged build uid can EXECUTE it (so that a leak of the
    // caller's wrapper into the build would actually run it), with the marker
    // somewhere it can WRITE (/tmp): see `reachable_marker`.
    let dir = test_parent().parent().unwrap().join("wrappers");
    std::fs::create_dir_all(&dir).unwrap();
    chmod(&dir, 0o755);
    let w = dir.join(marker.file_name().unwrap());
    write(
        &w,
        &format!("#!/bin/sh\n: > '{}'\nexec \"$@\"\n", marker.display()),
    );
    chmod_x(&w);
    w
}

/// A marker file path the build's unprivileged uid can create, removed at exit.
fn reachable_marker(name: &str) -> PathBuf {
    use std::sync::Mutex;
    static MARKS: Mutex<Vec<std::ffi::CString>> = Mutex::new(Vec::new());
    extern "C" fn clean() {
        if let Ok(m) = MARKS.lock() {
            for c in m.iter() {
                let _ = std::fs::remove_file(c.to_str().unwrap());
            }
        }
    }
    let p = PathBuf::from(format!("/tmp/axon-gbe-{}-{name}", std::process::id()));
    let _ = std::fs::remove_file(&p);
    let mut m = MARKS.lock().unwrap();
    if m.is_empty() {
        unsafe { libc::atexit(clean) };
    }
    m.push(std::ffi::CString::new(p.to_str().unwrap()).unwrap());
    p
}

