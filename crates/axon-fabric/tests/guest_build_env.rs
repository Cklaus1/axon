/// A kernel "source tarball" whose Makefile writes into vmlinux what its
/// recipe sees of the variables a caller could use to steer the compiler.
fn kernel_fixture(d: &Path) -> (PathBuf, PathBuf) {
    let src = d.join("ksrc/linux-0.0.1");
    write(
        &src.join("Makefile"),
        "olddefconfig:\n\t@true\nvmlinux:\n\t@printf 'kcflags=[%s] cc=[%s] cross=[%s] path=[%s]\\n' \
         \"$$KCFLAGS\" \"$(CC)\" \"$$CROSS_COMPILE\" \"$$PATH\" > vmlinux\n",
    );
    let dist = d.join("dist");
    std::fs::create_dir_all(&dist).unwrap();
    let st = Command::new("/usr/bin/tar")
        .arg("-C")
        .arg(d.join("ksrc"))
        .arg("-cJf")
        .arg(dist.join("linux-0.0.1.tar.xz"))
        .arg("linux-0.0.1")
        .status()
        .unwrap();
    assert!(st.success(), "setup: tar");
    let prof = d.join("prof");
    write(&prof.join("k.config"), "CONFIG_A=y\n");
    write(&prof.join("o.config"), "# overlay\nCONFIG_B=y\n");
    write(
        &prof.join("kernel.pin"),
        &format!(
            "KERNEL_VERSION=0.0.1\nKERNEL_TARBALL_SHA256={}\nKERNEL_CONFIG=k.config\n\
             KERNEL_CONFIG_SHA256={}\nKERNEL_OVERLAY=o.config\nKERNEL_OVERLAY_SHA256={}\n",
            sha(&dist.join("linux-0.0.1.tar.xz")),
            sha(&prof.join("k.config")),
            sha(&prof.join("o.config"))
        ),
    );
    (dist, prof)
}

fn kernel_step(r: &Path, dist: &Path, prof: &Path, env: &[(&str, String)]) -> Output {
    let mut c = gbe(r);
    c.arg("kernel")
        .arg(dist.join("kernel-build.json"))
        .arg(dist)
        .arg(prof);
    for (k, v) in env {
        c.env(k, v);
    }
    c.output().unwrap()
}

